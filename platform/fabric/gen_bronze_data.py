#!/usr/bin/env python3
"""
Generate MOCK Bronze-layer datasets for the AI FinOps accelerator.

Produces one CSV per MVP Bronze table defined in docs/bronze-layer-architecture.md,
grounded in the identities / apps / business units already in the repo dimensions so
the Bronze feeds conform cleanly in Silver.

EVERYTHING PRODUCED IS SYNTHETIC / MOCK. Rows carry lineage columns and a
_data_class='MOCK' marker so nothing is ever mistaken for real tenant data.

Output: platform/fabric/bronze_out/*.csv

REPRODUCIBILITY — the committed snapshot is byte-for-byte reproducible.
Every random draw is seeded (random.seed(42)) and every surrogate id is a stable
crc32 (see stable_id(); the built-in hash() is per-process random and must never
be used here). The only remaining variable is the date window, which anchors on
date.today() so the live demo never ages out; FINOPS_MOCK_END pins it. The
committed CSVs in bronze_out/ are pinned to 2026-09-08, regenerated in one run:

    FINOPS_MOCK_END=2026-09-08 python platform/fabric/gen_bronze_data.py   # bash
    $env:FINOPS_MOCK_END="2026-09-08"; python platform/fabric/gen_bronze_data.py  # PowerShell

Running that twice in two separate processes yields an identical bronze_out/.
"""
import csv
