random.seed(42)


def stable_id(text, mod):
    """A deterministic, process-independent surrogate id from a string.

    The built-in hash() of a str is randomized per process (PYTHONHASHSEED), so
    `abs(hash(login)) % N` silently produces DIFFERENT ids on every run even with
    random.seed(42) and FINOPS_MOCK_END pinned — which makes bronze_out/ non-
    reproducible and lets real data changes hide behind hash churn. crc32 is
    stable across processes and Python versions, so the committed snapshot can be
    regenerated byte-for-byte.
    """
    return zlib.crc32(str(text).encode()) % mod


