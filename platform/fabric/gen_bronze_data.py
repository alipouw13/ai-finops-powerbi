def gen_m365_cowork():
    # Microsoft 365 Copilot Cowork add-on consumption. Modelled on the two
    # surfaces the M365 admin center actually exposes (there is NO API):
    #   * Copilot -> Cost Management -> Consumption tab / CSV export (credits)
    #   * Copilot -> Cowork usage report (Total/Scheduled/User-initiated tasks)
    # The billing unit is the Copilot Credit at $0.01, NOT a "Cowork unit":
    # Cowork consumes a variable number of credits per task (model, context,
    # runtime, tools), so credits-per-task here is deliberately a spread, not a
    # constant. Cowork requires an existing M365 Copilot seat + usage-based
    # billing enabled; access is granted by a spending policy, not a licence.
    #
    # IMPORTANT (double-count): on the Azure bill these same credits appear under
    # ONE service labelled "Microsoft Copilot Studio" (Cowork + Studio + Work IQ
    # share the Copilot Credits meter). This MOCK feed is a separate, clearly
    # non-overlapping source; silver's Azure conform excludes that service so the
    # dollars are never counted twice.
    heavy = {"dev.patel", "jenny.oyelaran", "marco.silva"}   # a few heavy users
    policy = {
        "BU-TECH": "Cowork - Engineering", "BU-INSURANCE": "Cowork - Claims",
        "BU-RETAIL": "Cowork - Retail Ops", "BU-DISCOVERY": "Cowork - Discovery",
    }
    rows = []
    for d in MONTH_DAYS:
        for u in humans:
            # Idle seat holders (lee.novak, kim.arroyo) hold an M365 Copilot seat
            # but never touch Cowork -> the "seat holders with zero add-on use"
            # case the utilisation page needs. They simply emit no rows.
            if is_idle(u):
                continue
            is_heavy = u["identity_key"] in heavy
            # long tail: light users are active on Cowork only some days.
            if not is_heavy and random.random() > 0.35:
                continue
            user_initiated = (random.randint(6, 22) if is_heavy
                              else random.randint(1, 4))
            scheduled = (random.randint(2, 10) if is_heavy
                         else random.randint(0, 2))
            total_tasks = user_initiated + scheduled
            # Credits per task vary with model/context/runtime/tools; heavier
            # automations (scheduled agent runs) draw more.
            credits = sum(random.randint(25, 140) for _ in range(total_tasks))
            bu = u["home_business_unit_key"]
            rows.append({
                "report_date": d.isoformat(),
                "user_id": u["identity_key"],          # Entra object id
                "user_principal_name": u["upn"],
                "display_name": u["display_name"],
                "service": "Cowork",
                "spending_policy_name": policy.get(bu, "Cowork - Default"),
                "total_tasks": total_tasks,
                "scheduled_tasks": scheduled,
                "user_initiated_tasks": user_initiated,
                "credits_consumed": credits,
                "last_activity_date": d.isoformat(),
                **lineage("m365.admin.copilot.costmanagement+coworkusagereport",
                          d.isoformat()),
            })
    write("bronze_m365_cowork_usage", rows)


def gen_foundry_gateway():
    # APIM AI Gateway -> Log Analytics. This is the ONLY per-user Foundry token
    # attribution path: Azure Monitor metrics (bronze_azure_ai_metrics) are
    # resource-grain and carry no principal, so summing them lands every request
    # on 'unknown'. The gateway captures the Entra JWT (oid / client id) plus the
    # cc:/bu: claims the calling app forwards. Shaped on data/foundry_gateway_raw.json.
    #
    # Silver PREFERS this feed over bronze_azure_ai_metrics when it exists and
    # falls back when it does not - it never reads both, so the two token sources
    # can never double-count.
    #
    # Each service principal is a backend app; its client id doubles as the
    # ownership key so silver can attribute the spend to a real application_key
    # instead of APP-UNKNOWN. (The real equivalent is ApimClientOwnership_CL.)
    sp_app = {
        "checkout-service": ("APP-CHECKOUT", "BU-RETAIL", "CC-1000", "Retail"),
        "search-api": ("APP-SEARCH", "BU-DISCOVERY", "CC-2000", "Discovery"),
        "ds-notebooks": ("APP-DSNB", "BU-PLATFORM", "CC-3000", "Platform"),
        "mobile-assistant": ("APP-MOBILE", "BU-RETAIL", "CC-4000", "Retail"),
    }
    models = [("gpt-4.1-mini", "2025-04-14"), ("gpt-4.1", "2025-04-14")]
    regions = ["eastus2", "swedencentral"]
    rows = []
    for d in DAYS:
        # Backend service principals carry the bulk of Foundry traffic.
        for sp in sps:
            owned = sp_app.get(sp["display_name"])
            if not owned:
                continue
            app_key, bu, cc, bu_claim = owned
            for model, ver in random.sample(models, k=random.randint(1, 2)):
                requests = random.randint(200, 5000)
                pt = requests * random.randint(180, 900)
                gt = int(pt * random.uniform(0.3, 0.7))
                cached = int(pt * random.uniform(0.0, 0.25))
                err = random.random() < 0.03
                rows.append({
                    "time_generated": d.isoformat() + "T00:00:00Z",
                    "oid": "",                       # client-credentials call
                    "client_id": sp["identity_key"],
                    "app_id": sp["identity_key"],
                    "upn_or_app_name": sp["display_name"],
                    "business_unit_claim": bu_claim,
                    "cost_center_claim": cc,
                    "model_name": model,
                    "model_version": ver,
                    "deployment_region": random.choice(regions),
                    "prompt_tokens": pt,
                    "completion_tokens": gt,
                    "cached_prompt_tokens": cached,
                    "total_tokens": pt + gt,
                    "requests": requests,
                    "total_latency_ms": round(random.uniform(200, 3500), 1),
                    "status_code": 500 if err else 200,
                    "is_error": "True" if err else "False",
                    "is_streaming": random.choice(["True", "False"]),
                    "operation_name": "Chat Completions",
                    "api_name": "AI Gateway",
                    "backend_id": "aoai-finops.openai.azure.com",
                    "request_id": f"req-{d.isoformat()}-{sp['identity_key'][:8]}-{model}",
                    **lineage("apim.aigateway / loganalytics.ApiManagementGatewayLogs",
                              d.isoformat()),
                })
        # A lighter tail of interactive user calls (playground / notebooks),
        # attributed by Entra oid so they resolve to real people, not 'unknown'.
        for u in random.sample(ACTIVE_HUMANS, k=min(3, len(ACTIVE_HUMANS))):
            model, ver = random.choice(models)
            requests = random.randint(5, 120)
            pt = requests * random.randint(150, 600)
            gt = int(pt * random.uniform(0.3, 0.7))
            rows.append({
                "time_generated": d.isoformat() + "T00:00:00Z",
                "oid": u["identity_key"],
                "client_id": "",
                "app_id": "",
                "upn_or_app_name": u["upn"],
                "business_unit_claim": u["home_business_unit_key"],
                "cost_center_claim": u["cost_center_key"],
                "model_name": model,
                "model_version": ver,
                "deployment_region": random.choice(regions),
                "prompt_tokens": pt,
                "completion_tokens": gt,
                "cached_prompt_tokens": int(pt * random.uniform(0.0, 0.2)),
                "total_tokens": pt + gt,
                "requests": requests,
                "total_latency_ms": round(random.uniform(200, 3500), 1),
                "status_code": 200,
                "is_error": "False",
                "is_streaming": random.choice(["True", "False"]),
                "operation_name": "Chat Completions",
                "api_name": "AI Gateway",
                "backend_id": "aoai-finops.openai.azure.com",
                "request_id": f"req-{d.isoformat()}-{u['identity_key'][:8]}-{model}",
                **lineage("apim.aigateway / loganalytics.ApiManagementGatewayLogs",
                          d.isoformat()),
            })
    write("bronze_foundry_gateway", rows)


